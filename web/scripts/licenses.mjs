// Licence inventory of the web app's direct dependencies, read offline from node_modules/*/package.json.
// Usage: node scripts/licenses.mjs > ../docs/licenses/web-direct.md
import { readFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const rows = [];
for (const [group, deps] of [
  ["runtime", pkg.dependencies ?? {}],
  ["dev", pkg.devDependencies ?? {}],
]) {
  for (const name of Object.keys(deps).sort()) {
    try {
      const meta = JSON.parse(readFileSync(`node_modules/${name}/package.json`, "utf8"));
      const licence = typeof meta.license === "string" ? meta.license : (meta.license?.type ?? "see package");
      const repo = typeof meta.repository === "string" ? meta.repository : (meta.repository?.url ?? meta.homepage ?? "");
      rows.push(`| ${name} | ${meta.version} | ${licence} | ${group} | ${repo.replace(/^git\+/, "").replace(/\.git$/, "")} |`);
    } catch {
      rows.push(`| ${name} | not installed | – | ${group} | – |`);
    }
  }
}
console.log("# Web dependencies and licences\n\nGenerated by `node scripts/licenses.mjs` from the installed packages.\n");
console.log("| Package | Version | Licence | Scope | Source |\n|---|---|---|---|---|");
console.log(rows.join("\n"));
